public class BitManipulation {
    public static void main(String[] args) {

        // binary operators

        // Binary And operator
        System.out.println(5 & 6);

        // Binary OR operator
        System.out.println(5 | 6);

        // Binary XOR OPERATOR
        System.out.println(5 ^ 6);

        // Binary one's complement
        System.out.println(~5);

        // Binary left shift
        System.out.println(5 << 2);

        // Binary Right shift
        System.out.println(7 >> 2);
    }
}
